package de.kiwi.framework.web

import com.jayway.jsonpath.DocumentContext
import com.jayway.jsonpath.JsonPath
import de.kiwi.api.application.service.UserDescriptorProvider
import de.kiwi.api.domain.UserDescriptor
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.CsvSource
import org.springframework.boot.autoconfigure.EnableAutoConfiguration
import org.springframework.boot.persistence.autoconfigure.EntityScan
import org.springframework.boot.security.autoconfigure.SecurityAutoConfiguration
import org.springframework.boot.security.autoconfigure.UserDetailsServiceAutoConfiguration
import org.springframework.boot.security.autoconfigure.actuate.web.servlet.ManagementWebSecurityAutoConfiguration
import org.springframework.boot.security.autoconfigure.web.servlet.SecurityFilterAutoConfiguration
import org.springframework.boot.security.autoconfigure.web.servlet.ServletWebSecurityAutoConfiguration
import org.springframework.boot.test.context.runner.WebApplicationContextRunner
import org.springframework.context.annotation.Bean
import org.springframework.context.annotation.ComponentScan
import org.springframework.context.annotation.Configuration
import org.springframework.test.web.servlet.get
import org.springframework.test.web.servlet.setup.MockMvcBuilders

/**
 * Tests the OpenAPI document of the Kiwi endpoints generated by the [KiwiOpenApiAutoConfiguration], using the generic
 * test entities: Publisher (query, create, update, delete), Publication and Author (query, report).
 */
class KiwiOpenApiIntegrationTest {

    @Configuration
    @EnableAutoConfiguration(
        exclude = [
            SecurityAutoConfiguration::class,
            SecurityFilterAutoConfiguration::class,
            ServletWebSecurityAutoConfiguration::class,
            UserDetailsServiceAutoConfiguration::class,
            ManagementWebSecurityAutoConfiguration::class,
        ],
    )
    @ComponentScan("de.kiwi.framework.infrastructure.generic")
    @EntityScan("de.kiwi.api", "de.kiwi.framework.infrastructure.generic")
    class TestApplicationConfig {
        @Bean
        fun userDescriptorProvider() = UserDescriptorProvider { UserDescriptor.ANONYMOUS }
    }

    private val contextRunner = WebApplicationContextRunner()
        .withUserConfiguration(TestApplicationConfig::class.java)
        .withPropertyValues(
            "spring.datasource.url=jdbc:h2:mem:openapi-test",
            "spring.jpa.hibernate.ddl-auto=none",
            "spring.mustache.check-template-location=false",
            "spring.jpa.open-in-view=false",
        )

    private fun withApiDocs(vararg properties: String, assertions: (DocumentContext) -> Unit) {
        contextRunner.withPropertyValues(*properties).run { context ->
            assertThat(context).hasNotFailed()
            val mvc = MockMvcBuilders.webAppContextSetup(context).build()
            val response = mvc.get("/v3/api-docs").andReturn().response
            assertThat(response.status).describedAs(response.contentAsString).isEqualTo(200)
            assertions(JsonPath.parse(response.contentAsString))
        }
    }

    private fun DocumentContext.operations(path: String): Set<String> =
        paths()[path]?.let { @Suppress("UNCHECKED_CAST") (it as Map<String, Any>).keys } ?: emptySet()

    private fun DocumentContext.paths(): Map<String, Any> =
        read<Map<String, Any>>("$").get("paths")?.let { @Suppress("UNCHECKED_CAST") (it as Map<String, Any>) } ?: emptyMap()

    private fun DocumentContext.parameterNames(path: String, method: String): List<String> =
        read("$.paths['$path'].$method.parameters[*].name")

    @Test
    fun genericEntityOperations() = withApiDocs { doc ->
        // Operations per entity match the available generic commands and queries, updates are PATCH
        assertThat(doc.operations("/Publisher")).containsExactlyInAnyOrder("get", "post")
        assertThat(doc.operations("/Publisher/{id}")).containsExactlyInAnyOrder("get", "patch", "delete")
        assertThat(doc.operations("/Publisher/_schema")).containsExactly("get")
        assertThat(doc.operations("/Publication")).containsExactly("get")
        assertThat(doc.operations("/Publication/{id}")).containsExactly("get")

        // Only canonical entity names are documented
        assertThat(doc.paths().keys).allMatch { it.startsWith("/Publisher") || it.startsWith("/Publication") || it.startsWith("/Author") }

        assertThat(doc.read<String>("$.paths['/Publisher'].post.operationId")).isEqualTo("kiwi.command.Publisher.create")
        assertThat(doc.read<String>("$.paths['/Publisher/{id}'].patch.operationId")).isEqualTo("kiwi.command.Publisher.update")
        assertThat(doc.read<List<String>>("$.tags[*].name")).contains("kiwi.Publisher", "kiwi.Publication", "kiwi.Author")
    }

    @Test
    fun genericBodyCommandModels() = withApiDocs { doc ->
        val create = "$.paths['/Publisher'].post.requestBody.content['application/json'].schema"
        assertThat(doc.read<Boolean>("$create.additionalProperties")).isFalse()
        assertThat(doc.read<Map<String, Any>>("$create.properties").keys).containsExactly("name", "contact")
        assertThat(doc.read<List<String>>("$create.required")).containsExactlyInAnyOrder("name", "contact")
        assertThat(doc.read<String>("$create.properties.name.type")).isEqualTo("string")
        assertThat(doc.read<String>("$create.properties.contact['\$ref']")).isEqualTo("#/components/schemas/kiwi.dto.Contact")

        // Update commands are patches, without required properties
        val update = "$.paths['/Publisher/{id}'].patch.requestBody.content['application/json'].schema"
        assertThat(doc.read<Map<String, Any>>("$update.properties").keys).containsExactly("name", "contact")
        assertThat(doc.read<Map<String, Any>>(update)).doesNotContainKey("required")

        // Column value classes are registered as DTO schemas
        assertThat(doc.read<Map<String, Any>>("$.components.schemas['kiwi.dto.Contact'].properties"))
            .containsKeys("country", "city", "zipCode")
    }

    @Test
    fun entityIdAndUserDescriptorParameters() = withApiDocs { doc ->
        // EntityIds are documented as strings, UserDescriptor is not a parameter
        val idParameter = "$.paths['/Publisher/{id}'].patch.parameters[?(@.name == 'id')]"
        assertThat(doc.read<List<String>>("$idParameter.in")).containsExactly("path")
        assertThat(doc.read<List<String>>("$idParameter.schema.type")).containsExactly("string")
        assertThat(doc.read<List<String>>("$.paths..parameters[*].name")).doesNotContain("user")
    }

    @Test
    fun reportOperations() = withApiDocs { doc ->
        assertThat(doc.operations("/Publication/_report")).containsExactly("get")
        assertThat(doc.operations("/Publication/_report/_schema")).containsExactly("get")
        assertThat(doc.read<Map<String, Any>>("$.components.schemas").keys)
            .contains("kiwi.report.AnalyticalReport", "kiwi.report.Slice", "kiwi.report.meta.AnalyticalReportSchema")
    }

    @ParameterizedTest
    @CsvSource(
        "NoFilters, false, false, false",
        "EntityFiltersOnly, true, false, false",
        "EntityAndDefaultColumnFilters, true, true, false",
        "EntityAndAllColumnFilters, true, true, true",
    )
    fun queryParameterDetailLevels(
        level: String,
        entityFilters: Boolean,
        defaultColumnFilters: Boolean,
        operatorColumnFilters: Boolean,
    ) = withApiDocs("kiwi.web.open-api.query-params-details=$level") { doc ->
        val names = doc.parameterNames("/Publication", "get")
        assertThat(names).contains("_page", "_size", "_sort", "_fieldset")
        assertThat(names.contains("titleLike")).describedAs("entity filter").isEqualTo(entityFilters)
        assertThat(names.contains("description")).describedAs("default column filter").isEqualTo(defaultColumnFilters)
        assertThat(names.any { it.startsWith("title:") }).describedAs("operator column filter")
            .isEqualTo(operatorColumnFilters)
    }

    @Test
    fun disabledEndpointsAreNotDocumented() {
        withApiDocs("kiwi.web.generic-controller=false") { doc ->
            assertThat(doc.operations("/Publisher")).isEmpty()
            assertThat(doc.operations("/Publication/_report")).containsExactly("get")
        }
        withApiDocs("kiwi.web.report-controller=false") { doc ->
            assertThat(doc.operations("/Publisher")).containsExactlyInAnyOrder("get", "post")
            assertThat(doc.operations("/Publication/_report")).isEmpty()
        }
        withApiDocs("kiwi.web.open-api.enabled=false") { doc ->
            assertThat(doc.paths().keys).noneMatch { it.startsWith("/Publisher") }
        }
    }
}
